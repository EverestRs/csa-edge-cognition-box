from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def load_review(path: Path) -> list[dict[str, Any]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise RuntimeError("review json should be an object")
    items = data.get("items", [])
    if not isinstance(items, list):
        raise RuntimeError("review json missing items list")
    return [item for item in items if isinstance(item, dict)]


def resolve_target_class(item: dict[str, Any]) -> str:
    override = str(item.get("review_target_class", "")).strip()
    if override:
        return override
    return str(item.get("suggested_target_class", "")).strip()


def normalize_status(value: Any) -> str:
    return str(value or "").strip().lower()


def main() -> None:
    parser = argparse.ArgumentParser(description="Build target-intervals json from reviewed temporal candidates")
    parser.add_argument("--review", required=True, help="review json generated by build_temporal_review_pack.py")
    parser.add_argument("--output", required=True, help="output intervals json for --target-intervals")
    parser.add_argument("--include-status", default="approved", help="comma separated statuses to include")
    parser.add_argument("--video-filter", default="", help="optional exact video path filter, e.g. data\\laying_backward_1-1.mp4")
    args = parser.parse_args()

    include_status = {s.strip().lower() for s in str(args.include_status).split(",") if s.strip()}
    if not include_status:
        include_status = {"approved"}

    items = load_review(Path(args.review))
    intervals: list[dict[str, Any]] = []
    video_filter = str(args.video_filter or "").strip()

    for item in items:
        status = normalize_status(item.get("review_status", ""))
        if status not in include_status:
            continue

        item_video = str(item.get("video", "")).strip()
        if video_filter and item_video != video_filter:
            continue

        target_class = resolve_target_class(item)
        if not target_class:
            continue

        start_frame = int(item.get("start_frame", -1))
        end_frame = int(item.get("end_frame", -1))
        if start_frame <= 0 or end_frame <= 0:
            continue
        if end_frame < start_frame:
            start_frame, end_frame = end_frame, start_frame

        intervals.append(
            {
                "start_frame": start_frame,
                "end_frame": end_frame,
                "target_class": target_class,
                "source_id": str(item.get("id", "")),
                "video": item_video,
                "review_note": str(item.get("review_note", "")),
            }
        )

    payload = {
        "intervals": intervals,
        "meta": {
            "source_review": str(args.review),
            "included_status": sorted(include_status),
            "video_filter": video_filter,
            "count": len(intervals),
        },
    }

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    print(json.dumps({"output": str(out_path), "intervals": len(intervals)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
